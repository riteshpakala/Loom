#!/usr/bin/env python3
"""
Convert an app generated by Granite's create-granite-app.sh into the Loom layout.

    python3 adopt_loom_layout.py <path-to-generated-app>

What it does (and only on a freshly generated app; it refuses if the layout
already looks converted):

  Shared/Components/<X>        -> Components/<X>
  Shared/Services/<X>          -> Services/<X>Service   (files renamed X.swift -> XService.swift, X+Center -> XService+Center,
                                                          Reducers/X.Verb.swift -> Reducers/XService.Verb.swift)
  Shared/Utilities/Extensions  -> Shared/Extensions
  Shared/Utilities/*           -> Shared/Utility
  struct <Name>Component       -> struct <Name>   (every reference in every .swift file)
  + Shared/AppDelegate.swift      (iOS + macOS, from ../assets/AppDelegate.swift)
  + delegate adaptors in Shared/App.swift
  + Shared/Design/Brand.swift
  + Components/ and Services/ as synchronized folders on both app targets in the .xcodeproj
"""
import os
import re
import secrets
import shutil
import sys

ASSETS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets")


def fail(msg):
    print(f"✗ {msg}", file=sys.stderr)
    sys.exit(1)


def swift_files(root):
    for base, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if not d.startswith(".") and not d.endswith(".xcodeproj") and d != "Packages"]
        for f in files:
            if f.endswith(".swift"):
                yield os.path.join(base, f)


def rewrite(path, fn):
    with open(path) as fh:
        before = fh.read()
    after = fn(before)
    if after != before:
        with open(path, "w") as fh:
            fh.write(after)


def find_project(app):
    projects = [p for p in os.listdir(app) if p.endswith(".xcodeproj")]
    if len(projects) != 1:
        fail(f"expected one .xcodeproj in {app}, found {projects}")
    return os.path.join(app, projects[0], "project.pbxproj")


def move_services(app):
    src = os.path.join(app, "Shared", "Services")
    dst = os.path.join(app, "Services")
    os.makedirs(dst, exist_ok=True)
    for name in sorted(os.listdir(src)):
        folder = os.path.join(src, name)
        if not os.path.isdir(folder):
            continue
        service = name if name.endswith("Service") else name + "Service"
        target = os.path.join(dst, service)
        shutil.move(folder, target)
        # X.swift, X+Center.swift, Reducers/X.Verb.swift -> XService...
        for base, _, files in os.walk(target):
            for f in files:
                if f.endswith(".swift") and not f.startswith(service) and re.match(rf"^{re.escape(name)}[.+]", f):
                    os.rename(os.path.join(base, f), os.path.join(base, service + f[len(name):]))
        print(f"✓ Services/{service}")
    os.rmdir(src)


def move_components(app):
    shutil.move(os.path.join(app, "Shared", "Components"), os.path.join(app, "Components"))
    print("✓ Components/")


def split_utilities(app):
    util = os.path.join(app, "Shared", "Utilities")
    if not os.path.isdir(util):
        return
    ext = os.path.join(util, "Extensions")
    if os.path.isdir(ext):
        shutil.move(ext, os.path.join(app, "Shared", "Extensions"))
        print("✓ Shared/Extensions")
    if os.listdir(util):
        shutil.move(util, os.path.join(app, "Shared", "Utility"))
        print("✓ Shared/Utility")
    else:
        os.rmdir(util)


def rename_components(app):
    names = set()
    for path in swift_files(app):
        with open(path) as fh:
            names.update(re.findall(r"struct (\w+)Component\s*:\s*GraniteComponent", fh.read()))
    for path in swift_files(app):
        rewrite(path, lambda s: re.sub(r"\b(" + "|".join(map(re.escape, names)) + r")Component\b", r"\1", s) if names else s)
    for n in sorted(names):
        print(f"✓ {n}Component -> {n}")


def add_app_delegate(app):
    shared = os.path.join(app, "Shared")
    shutil.copy(os.path.join(ASSETS, "AppDelegate.swift"), os.path.join(shared, "AppDelegate.swift"))
    adaptors = (
        "    #if os(iOS)\n"
        "    @UIApplicationDelegateAdaptor(AppDelegate.self) var appDelegate\n"
        "    #elseif os(macOS)\n"
        "    @NSApplicationDelegateAdaptor(AppDelegate.self) var appDelegate\n"
        "    #endif\n\n"
    )

    def patch(s):
        s, n = re.subn(r"(@main\s*\n\s*struct \w+\s*:\s*App\s*\{\n)", r"\1" + adaptors.replace("\\", "\\\\"), s, count=1)
        if n != 1:
            fail("could not find `@main struct …: App {` in Shared/App.swift")
        return s

    rewrite(os.path.join(shared, "App.swift"), patch)
    print("✓ Shared/AppDelegate.swift (+ adaptors in Shared/App.swift)")


def add_design(app):
    design = os.path.join(app, "Shared", "Design")
    os.makedirs(design, exist_ok=True)
    brand = os.path.join(design, "Brand.swift")
    if not os.path.exists(brand):
        shutil.copy(os.path.join(ASSETS, "Brand.swift"), brand)
    print("✓ Shared/Design/Brand.swift")


def new_id(pbx):
    while True:
        candidate = secrets.token_hex(12).upper()
        if candidate not in pbx:
            return candidate


def sync_folders_in_project(pbxproj, folders):
    with open(pbxproj) as fh:
        s = fh.read()
    if "PBXFileSystemSynchronizedRootGroup" not in s:
        fail("project does not use synchronized folders; add Components/ and Services/ to the targets in Xcode by hand")

    shared = re.search(r"(\w{24}) /\* Shared \*/ = \{\n\t\t\tisa = PBXFileSystemSynchronizedRootGroup;", s)
    if not shared:
        fail("no synchronized Shared folder found in the project")
    shared_ref = f"{shared.group(1)} /* Shared */"

    for folder in folders:
        if re.search(rf"/\* {folder} \*/ = \{{\n\t\t\tisa = PBXFileSystemSynchronizedRootGroup;", s):
            continue
        ref = f"{new_id(s)} /* {folder} */"
        group = (f"\t\t{ref} = {{\n\t\t\tisa = PBXFileSystemSynchronizedRootGroup;\n"
                 f"\t\t\tpath = {folder};\n\t\t\tsourceTree = \"<group>\";\n\t\t}};\n")
        s = s.replace("/* End PBXFileSystemSynchronizedRootGroup section */",
                      group + "/* End PBXFileSystemSynchronizedRootGroup section */", 1)
        # main group and every target that compiles Shared/ also compiles the new folder
        s = s.replace(f"\t\t\t\t{shared_ref},\n", f"\t\t\t\t{shared_ref},\n\t\t\t\t{ref},\n")
        print(f"✓ {folder}/ added to the project")

    with open(pbxproj, "w") as fh:
        fh.write(s)


def main():
    if len(sys.argv) != 2:
        fail("usage: adopt_loom_layout.py <path-to-generated-app>")
    app = os.path.abspath(sys.argv[1])
    pbxproj = find_project(app)

    if os.path.isdir(os.path.join(app, "Components")) or os.path.isdir(os.path.join(app, "Services")):
        fail("Components/ or Services/ already at the root; this app looks converted already")
    for required in ("Shared/App.swift", "Shared/Components", "Shared/Services"):
        if not os.path.exists(os.path.join(app, required)):
            fail(f"missing {required}; run this on the output of create-granite-app.sh")

    move_components(app)
    move_services(app)
    split_utilities(app)
    rename_components(app)
    add_app_delegate(app)
    add_design(app)
    sync_folders_in_project(pbxproj, ["Components", "Services"])
    print("Done. Build both schemes, then run check_layout.py.")


if __name__ == "__main__":
    main()
